import { createHash, timingSafeEqual } from "node:crypto";
import type { IncomingMessage, ServerResponse } from "node:http";
import { RUN_LIMITS_V1 } from "../orchestration/limits.ts";
import type { RunServiceResult } from "./runs.ts";

/** Operations the authenticated API exposes; `RunService` implements them. */
export interface RunServiceApi {
  submit(body: unknown): Promise<RunServiceResult>;
  list(limit: number, repositoryId?: string): Promise<RunServiceResult>;
  get(runId: string): Promise<RunServiceResult>;
  events(runId: string, after: number, limit: number): Promise<RunServiceResult>;
  control(runId: string, body: unknown): Promise<RunServiceResult>;
}

export interface ServiceApiOptions {
  /** Bearer token generated by the launcher into the protected runtime credentials. */
  readonly token: string;
  readonly runs: RunServiceApi;
  readonly health: () => { readonly live: boolean; readonly ready: boolean };
  readonly maxBodyBytes?: number;
  readonly onError?: (error: unknown) => void;
}

const LOOPBACK_HOSTS = new Set(["127.0.0.1", "localhost", "[::1]"]);
const RUN_PATH = /^\/v1\/runs\/(run_[0-9a-f]{32})(\/events|\/controls)?$/;
export const MIN_API_TOKEN_LENGTH = 32;

class HttpError extends Error {
  constructor(readonly status: number, readonly code: string, message: string) {
    super(message);
  }
}

function digest(value: string): Buffer {
  return createHash("sha256").update(value, "utf8").digest();
}

function send(response: ServerResponse, status: number, body: unknown, headers: Record<string, string> = {}): void {
  const payload = JSON.stringify(body);
  response.writeHead(status, {
    "content-type": "application/json; charset=utf-8",
    "content-length": Buffer.byteLength(payload),
    "cache-control": "no-store",
    "x-content-type-options": "nosniff",
    ...headers,
  });
  response.end(payload);
}

/** Host header without port; only loopback names are accepted (DNS-rebinding defense). */
export function isLoopbackHost(host: string | undefined): boolean {
  if (!host) return false;
  const name = host.startsWith("[") ? host.slice(0, host.indexOf("]") + 1) : host.split(":")[0]!;
  return LOOPBACK_HOSTS.has(name.toLowerCase());
}

async function readJson(request: IncomingMessage, maxBytes: number): Promise<unknown> {
  const type = request.headers["content-type"]?.split(";")[0]?.trim().toLowerCase();
  if (type !== "application/json") throw new HttpError(415, "unsupported-media-type", "Requests must be application/json");
  const declared = Number(request.headers["content-length"] ?? "0");
  if (declared > maxBytes) throw new HttpError(413, "body-too-large", `Request body exceeds ${maxBytes} bytes`);
  const chunks: Buffer[] = [];
  let size = 0;
  for await (const chunk of request) {
    size += (chunk as Buffer).length;
    if (size > maxBytes) throw new HttpError(413, "body-too-large", `Request body exceeds ${maxBytes} bytes`);
    chunks.push(chunk as Buffer);
  }
  try {
    return JSON.parse(Buffer.concat(chunks).toString("utf8"));
  } catch {
    throw new HttpError(400, "invalid-json", "Request body is not valid JSON");
  }
}

function integer(value: string | null, fallback: number): number {
  if (value === null || value === "") return fallback;
  return /^\d{1,15}$/.test(value) ? Number(value) : Number.NaN;
}

function deliver(response: ServerResponse, result: RunServiceResult): void {
  if (result.ok) send(response, result.status, result.body);
  else send(response, result.status, { error: { code: result.code, message: result.detail } });
}

/**
 * Local execution API. Health probes stay unauthenticated; every `/v1` route
 * requires the bearer token, a loopback Host, and no browser Origin (browser
 * sessions arrive with the operator-session work in P5-05).
 */
export function createServiceApiHandler(options: ServiceApiOptions): (request: IncomingMessage, response: ServerResponse) => void {
  if (options.token.length < MIN_API_TOKEN_LENGTH) {
    throw new Error(`The service API token must be at least ${MIN_API_TOKEN_LENGTH} characters`);
  }
  const expected = digest(options.token);
  const maxBodyBytes = options.maxBodyBytes ?? RUN_LIMITS_V1.maxWorkflowInputBytes + 64 * 1024;

  const authorized = (request: IncomingMessage): boolean => {
    const header = request.headers.authorization;
    if (typeof header !== "string" || !header.startsWith("Bearer ")) return false;
    return timingSafeEqual(digest(header.slice(7)), expected);
  };

  const route = async (request: IncomingMessage, response: ServerResponse): Promise<void> => {
    const url = new URL(request.url ?? "/", "http://localhost");
    const method = request.method ?? "GET";
    if (url.pathname === "/health/live" || url.pathname === "/health/ready") {
      if (method !== "GET") throw new HttpError(405, "method-not-allowed", "Use GET");
      const health = options.health();
      const ok = url.pathname === "/health/live" ? health.live : health.ready;
      send(response, ok ? 200 : 503, { ready: ok });
      return;
    }
    if (!url.pathname.startsWith("/v1/")) throw new HttpError(404, "not-found", "Unknown route");
    if (!isLoopbackHost(request.headers.host)) throw new HttpError(421, "invalid-host", "The API only answers loopback host names");
    if (request.headers.origin !== undefined) {
      throw new HttpError(403, "browser-origin-rejected", "Browser requests are not accepted by the local API");
    }
    if (!authorized(request)) {
      response.setHeader("www-authenticate", "Bearer");
      throw new HttpError(401, "unauthenticated", "A valid bearer token is required");
    }
    if (!options.health().ready) throw new HttpError(503, "not-ready", "The execution service is not ready");

    if (url.pathname === "/v1/runs") {
      if (method === "POST") return deliver(response, await options.runs.submit(await readJson(request, maxBodyBytes)));
      if (method === "GET") {
        return deliver(response, await options.runs.list(
          integer(url.searchParams.get("limit"), 50),
          url.searchParams.get("repositoryId") ?? undefined,
        ));
      }
      throw new HttpError(405, "method-not-allowed", "Use GET or POST");
    }
    const match = RUN_PATH.exec(url.pathname);
    if (!match) throw new HttpError(404, "not-found", "Unknown route");
    const [, runId, child] = match;
    if (child === "/controls") {
      if (method !== "POST") throw new HttpError(405, "method-not-allowed", "Use POST");
      return deliver(response, await options.runs.control(runId!, await readJson(request, 64 * 1024)));
    }
    if (method !== "GET") throw new HttpError(405, "method-not-allowed", "Use GET");
    if (child === "/events") {
      return deliver(response, await options.runs.events(
        runId!,
        integer(url.searchParams.get("after"), 0),
        integer(url.searchParams.get("limit"), 100),
      ));
    }
    return deliver(response, await options.runs.get(runId!));
  };

  return (request, response) => {
    route(request, response).catch((error: unknown) => {
      if (error instanceof HttpError) {
        send(response, error.status, { error: { code: error.code, message: error.message } });
      } else {
        options.onError?.(error);
        if (!response.headersSent) send(response, 500, { error: { code: "internal-error", message: "The request failed" } });
        else response.destroy();
      }
      // Drain an unread body so the connection can be reused or closed cleanly.
      if (!request.complete) request.resume();
    });
  };
}
